-- Guest replies belong to published orders. Public visitors can submit through
-- the RPC only; company members and administrators can read their order replies.
create table public.order_rsvps (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  submission_token uuid not null,
  full_name text not null check (length(btrim(full_name)) between 1 and 120),
  attendance text not null check (attendance in ('yes', 'no')),
  guest_count integer not null,
  additional_guests text[] not null default '{}',
  message text not null default '' check (length(message) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (order_id, submission_token),
  constraint order_rsvp_guest_count_valid check (
    (attendance = 'yes' and guest_count between 1 and 10
      and cardinality(additional_guests) = guest_count - 1)
    or (attendance = 'no' and guest_count = 0 and cardinality(additional_guests) = 0)
  )
);

create index order_rsvps_order_created_idx on public.order_rsvps(order_id, created_at desc);
create trigger order_rsvps_touch_updated_at before update on public.order_rsvps
for each row execute function public.touch_updated_at();

alter table public.order_rsvps enable row level security;
revoke all on public.order_rsvps from public, anon, authenticated;
revoke all on sequence public.order_rsvps_id_seq from public, anon, authenticated;
grant select on public.order_rsvps to authenticated;

create policy "order replies visible to company and admins"
on public.order_rsvps for select to authenticated
using (
  public.current_user_is_admin()
  or exists (
    select 1 from public.orders o
    where o.id = order_rsvps.order_id
      and o.company_id = public.current_user_company_id()
  )
);

create or replace function public.submit_order_rsvp(
  p_order_id bigint,
  p_published_path text,
  p_submission_token uuid,
  p_full_name text,
  p_attendance text,
  p_guest_count integer,
  p_additional_guests text[],
  p_message text
) returns jsonb
language plpgsql security definer set search_path = public
as $$
begin
  -- Resolve the path and ID together; never accept replies to drafts or expired orders.
  perform 1 from public.orders
  where id = p_order_id and published_path = p_published_path
    and status = 'READY' and (expires_at is null or expires_at > now())
  for share;
  if not found then
    raise exception 'This invitation is no longer accepting replies.';
  end if;

  if p_submission_token is null then
    raise exception 'A reply token is required. Please reload the invitation.';
  end if;
  if p_full_name is null or length(btrim(p_full_name)) not between 1 and 120 then
    raise exception 'Please enter a full name of up to 120 characters.';
  end if;
  if p_attendance is null or p_attendance not in ('yes', 'no') then
    raise exception 'Please select whether you will be attending.';
  end if;
  if p_guest_count is null or p_additional_guests is null
    or coalesce(array_ndims(p_additional_guests), 1) <> 1 then
    raise exception 'Please enter valid guest details.';
  end if;
  if (p_attendance = 'yes' and (p_guest_count not between 1 and 10
      or cardinality(p_additional_guests) <> p_guest_count - 1))
    or (p_attendance = 'no' and (p_guest_count <> 0 or cardinality(p_additional_guests) <> 0)) then
    raise exception 'The guest count must match the names provided.';
  end if;
  if exists (
    select 1 from unnest(p_additional_guests) as guests(name)
    where name is null or length(btrim(name)) not between 1 and 120
  ) then
    raise exception 'Please enter each additional guest name (up to 120 characters).';
  end if;
  if length(coalesce(p_message, '')) > 1000 then
    raise exception 'Please keep your message within 1000 characters.';
  end if;

  insert into public.order_rsvps (
    order_id, submission_token, full_name, attendance, guest_count, additional_guests, message
  ) values (
    p_order_id, p_submission_token, btrim(p_full_name), p_attendance, p_guest_count,
    array(select btrim(name) from unnest(p_additional_guests) as guests(name)),
    btrim(coalesce(p_message, ''))
  )
  on conflict (order_id, submission_token) do update
  set full_name = excluded.full_name,
      attendance = excluded.attendance,
      guest_count = excluded.guest_count,
      additional_guests = excluded.additional_guests,
      message = excluded.message;

  return jsonb_build_object('saved', true);
end;
$$;

revoke all on function public.submit_order_rsvp(bigint, text, uuid, text, text, integer, text[], text) from public;
grant execute on function public.submit_order_rsvp(bigint, text, uuid, text, text, integer, text[], text) to anon, authenticated;

-- Return the database order ID explicitly, including for legacy one-segment URLs.
create or replace function public.get_published_invitation(p_path text)
returns jsonb language sql stable security definer set search_path = public
as $$
  select jsonb_build_object(
    'orderId', o.id::text, 'slug', o.published_path,
    'details', o.form_data, 'createdAt', o.published_at
  )
  from public.orders o
  where o.published_path = p_path and o.status = 'READY'
    and (o.expires_at is null or o.expires_at > now())
  limit 1
$$;
revoke all on function public.get_published_invitation(text) from public;
grant execute on function public.get_published_invitation(text) to anon, authenticated;
