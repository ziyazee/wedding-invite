create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  created_by uuid not null references auth.users(id),
  template_code text not null,
  groom_name text not null,
  bride_name text not null,
  phone_number text not null,
  form_data jsonb not null default '{}'::jsonb,
  status text not null default 'CREATED' check (status in ('CREATED','IN_PROGRESS','READY','REJECTED')),
  published_path text unique,
  published_url text,
  published_at timestamptz,
  expires_at timestamptz,
  rejection_reason text,
  admin_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint valid_expiry_date check (expires_at is null or published_at is null or expires_at > published_at),
  constraint published_path_format check (published_path is null or published_path ~ '^([a-z0-9]{1,80}|[0-9]+/[a-z0-9]{1,80})$'),
  constraint published_order_has_path check (status <> 'READY' or (published_path is not null and published_url is not null and published_at is not null))
);

create index if not exists orders_company_id_idx on public.orders(company_id);
create index if not exists orders_status_idx on public.orders(status);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_expires_at_idx on public.orders(expires_at);
create unique index if not exists companies_email_login_idx on public.companies(lower(email)) where email is not null;
create or replace function public.current_user_is_admin() returns boolean
language sql stable security definer set search_path = public
as $$ select upper(coalesce(auth.jwt()->'app_metadata'->>'role', '')) = 'ADMIN' $$;

create or replace function public.current_user_company_id() returns bigint
language sql stable security definer set search_path = public
as $$
  select c.id from public.companies c
  where lower(c.email) = lower(auth.jwt()->>'email')
  limit 1
$$;

create or replace function public.touch_updated_at() returns trigger
language plpgsql set search_path = public
as $$ begin new.updated_at = now(); return new; end $$;

drop trigger if exists companies_touch_updated_at on public.companies;
create trigger companies_touch_updated_at before update on public.companies for each row execute function public.touch_updated_at();
drop trigger if exists templates_touch_updated_at on public.invitation_templates;
create trigger templates_touch_updated_at before update on public.invitation_templates for each row execute function public.touch_updated_at();
drop trigger if exists orders_touch_updated_at on public.orders;
create trigger orders_touch_updated_at before update on public.orders for each row execute function public.touch_updated_at();

create or replace function public.validate_order_payload() returns trigger
language plpgsql set search_path = public
as $$
declare event_item jsonb;
begin
  if jsonb_typeof(new.form_data) <> 'object'
    or nullif(trim(new.groom_name),'') is null
    or nullif(trim(new.bride_name),'') is null
    or nullif(trim(new.phone_number),'') is null
    or new.form_data->>'groom' is distinct from new.groom_name
    or new.form_data->>'bride' is distinct from new.bride_name then
    raise exception 'Order names and phone number must match valid invitation details.';
  end if;
  if not exists (select 1 from public.invitation_templates where id=(new.form_data->>'template')::integer and template_code=new.template_code and is_active) then
    raise exception 'The selected invitation template is not active.';
  end if;
  if jsonb_typeof(new.form_data->'events') is distinct from 'array'
    or coalesce(jsonb_array_length(new.form_data->'events'), 0) < 1
    or coalesce(jsonb_array_length(new.form_data->'events'), 0) > 10 then
    raise exception 'An order must contain between one and ten event details.';
  end if;
  if nullif(trim(new.form_data->>'date'),'') is null
    or new.form_data->>'date' !~ '^\d{4}-\d{2}-\d{2}$'
    or coalesce(new.form_data->>'time','') !~ '^([01]\d|2[0-3]):[0-5]\d$'
    or coalesce(new.form_data->>'offset','') !~ '^[+-](0\d|1[0-4]):(00|15|30|45)$'
    or nullif(trim(new.form_data->>'venue'),'') is null
    or nullif(trim(new.form_data->>'address'),'') is null then
    raise exception 'Wedding date, time, venue, and address are required.';
  end if;
  for event_item in select value from jsonb_array_elements(new.form_data->'events') loop
    if nullif(trim(event_item->>'title'),'') is null or nullif(trim(event_item->>'date'),'') is null
      or event_item->>'date' !~ '^\d{4}-\d{2}-\d{2}$'
      or coalesce(event_item->>'time','') !~ '^([01]\d|2[0-3]):[0-5]\d$'
      or nullif(trim(event_item->>'venue'),'') is null
      or nullif(trim(event_item->>'address'),'') is null then
      raise exception 'Each celebration needs a name, date, time, venue, and address.';
    end if;
  end loop;
  return new;
end $$;
drop trigger if exists orders_validate_payload on public.orders;
create trigger orders_validate_payload before insert or update of form_data, template_code, groom_name, bride_name, phone_number on public.orders for each row execute function public.validate_order_payload();

