grant insert (company_id, created_by, template_code, groom_name, bride_name, phone_number, form_data) on public.orders to authenticated;
grant update (company_id, created_by, template_code, groom_name, bride_name, phone_number, form_data, status, published_path, published_url, published_at, expires_at, rejection_reason, admin_notes) on public.orders to authenticated;
grant usage, select on sequence public.orders_id_seq to authenticated;

