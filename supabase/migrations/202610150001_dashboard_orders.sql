drop policy if exists "company visible to members and admins" on public.companies;
create policy "company visible to members and admins" on public.companies for select to authenticated
using (public.current_user_is_admin() or id = public.current_user_company_id());
drop policy if exists "active templates visible to signed in users" on public.invitation_templates;
create policy "active templates visible to signed in users" on public.invitation_templates for select to authenticated
using (is_active or public.current_user_is_admin());
drop policy if exists "orders visible to company and admins" on public.orders;
create policy "orders visible to company and admins" on public.orders for select to authenticated
using (public.current_user_is_admin() or company_id = public.current_user_company_id());
drop policy if exists "clients create own company orders" on public.orders;
create policy "clients create own company orders" on public.orders for insert to authenticated
with check (
  public.current_user_is_admin() or (
    status = 'CREATED' and published_path is null and published_url is null and published_at is null and expires_at is null and rejection_reason is null and admin_notes is null
    and created_by = auth.uid()
    and company_id = public.current_user_company_id()
  )
);
drop policy if exists "admins process orders" on public.orders;
create policy "admins process orders" on public.orders for update to authenticated
using (public.current_user_is_admin()) with check (public.current_user_is_admin());

-- Public pages receive only the invitation payload for an explicitly published path.
create or replace function public.get_published_invitation(p_path text)
returns jsonb language sql stable security definer set search_path = public
as $$
  select jsonb_build_object('slug', o.published_path, 'details', o.form_data, 'createdAt', o.published_at)
  from public.orders o where o.published_path = p_path and o.status = 'READY' and (o.expires_at is null or o.expires_at > now()) limit 1
$$;
revoke all on function public.get_published_invitation(text) from public;
grant execute on function public.get_published_invitation(text) to anon, authenticated;

grant select on public.companies, public.invitation_templates, public.orders to authenticated;
