-- Venue images: per-company library of hall/auditorium photos used as footer
-- illustrations in the Embroidered Garden template.
-- Images live in the "venue-images" storage bucket under {company_id}/filename.
-- Each company can only see and manage its own rows.

-- Storage bucket (private)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'venue-images',
  'venue-images',
  false,
  10485760, -- 10 MB
  array['image/webp','image/jpeg','image/png']
)
on conflict (id) do nothing;

-- Storage RLS: authenticated company members access only their own folder
create policy "venue images: company read own"
  on storage.objects for select
  using (
    bucket_id = 'venue-images'
    and (
      public.current_user_is_admin()
      or split_part(name, '/', 1)::bigint = public.current_user_company_id()
    )
  );

create policy "venue images: company insert own"
  on storage.objects for insert
  with check (
    bucket_id = 'venue-images'
    and (
      public.current_user_is_admin()
      or split_part(name, '/', 1)::bigint = public.current_user_company_id()
    )
  );

create policy "venue images: company delete own"
  on storage.objects for delete
  using (
    bucket_id = 'venue-images'
    and (
      public.current_user_is_admin()
      or split_part(name, '/', 1)::bigint = public.current_user_company_id()
    )
  );

-- Table
create table if not exists public.venue_images (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  name text not null,
  storage_path text not null,
  created_at timestamptz not null default now()
);

create index if not exists venue_images_company_id_idx on public.venue_images(company_id);

alter table public.venue_images enable row level security;

create policy "venue images: company select own"
  on public.venue_images for select
  using (public.current_user_is_admin() or company_id = public.current_user_company_id());

create policy "venue images: company insert own"
  on public.venue_images for insert
  with check (public.current_user_is_admin() or company_id = public.current_user_company_id());

create policy "venue images: company delete own"
  on public.venue_images for delete
  using (public.current_user_is_admin() or company_id = public.current_user_company_id());

grant select, insert, delete on public.venue_images to authenticated;

