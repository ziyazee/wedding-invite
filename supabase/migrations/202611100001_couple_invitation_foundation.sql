-- Add a couple-level parent and invitation children without rewriting existing
-- orders. Each current order is copied as one couple and one invitation, while
-- its original row, status, links, and RSVP foreign keys remain intact.
begin;

create table public.couple_orders (
  id bigint generated by default as identity primary key,
  legacy_order_id bigint unique references public.orders(id) on delete cascade,
  company_id bigint not null references public.companies(id) on delete cascade,
  created_by uuid not null references auth.users(id),
  groom_name text not null,
  bride_name text not null,
  bride_first boolean not null default false,
  phone_number text not null,
  status text not null default 'CREATED'
    check (status in ('CREATED', 'IN_PROGRESS', 'READY', 'REJECTED')),
  price numeric,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index couple_orders_company_created_idx
  on public.couple_orders(company_id, created_at desc);

create table public.invitations (
  id bigint generated by default as identity primary key,
  couple_order_id bigint not null references public.couple_orders(id) on delete cascade,
  legacy_order_id bigint unique references public.orders(id) on delete cascade,
  template_code text not null,
  form_data jsonb not null default '{}'::jsonb,
  status text not null default 'CREATED'
    check (status in ('CREATED', 'IN_PROGRESS', 'READY', 'REJECTED')),
  published_path text unique,
  published_url text,
  management_id text unique,
  published_at timestamptz,
  expires_at timestamptz,
  rejection_reason text,
  admin_notes text,
  price numeric,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint invitation_valid_expiry_date
    check (expires_at is null or published_at is null or expires_at > published_at),
  constraint invitation_published_path_format check (
    published_path is null
    or published_path ~ '^([a-z][a-z0-9.-]{0,79}|[0-9]+/[a-z0-9]{1,80})$'
  ),
  constraint invitation_ready_has_path check (
    status <> 'READY'
    or (published_path is not null and published_url is not null and published_at is not null)
  )
);

create index invitations_couple_order_idx on public.invitations(couple_order_id, created_at);
create index invitations_status_idx on public.invitations(status);

drop trigger if exists couple_orders_touch_updated_at on public.couple_orders;
create trigger couple_orders_touch_updated_at before update on public.couple_orders
for each row execute function public.touch_updated_at();
drop trigger if exists invitations_touch_updated_at on public.invitations;
create trigger invitations_touch_updated_at before update on public.invitations
for each row execute function public.touch_updated_at();

alter table public.couple_orders enable row level security;
alter table public.invitations enable row level security;
revoke all on public.couple_orders, public.invitations from public, anon, authenticated;
grant select on public.couple_orders, public.invitations to authenticated;
grant usage, select on sequence public.couple_orders_id_seq to authenticated;
grant usage, select on sequence public.invitations_id_seq to authenticated;

create policy "couple orders visible to owner and admins" on public.couple_orders
for select to authenticated using (
  public.current_user_is_admin() or company_id = public.current_user_company_id()
);
create policy "invitations visible to owner and admins" on public.invitations
for select to authenticated using (
  public.current_user_is_admin()
  or exists (
    select 1 from public.couple_orders c
    where c.id = invitations.couple_order_id
      and c.company_id = public.current_user_company_id()
  )
);

-- Copy every live order one-to-one. ON CONFLICT makes the backfill safe to
-- re-run and source IDs provide a stable audit/rollback mapping.
insert into public.couple_orders (
  legacy_order_id, company_id, created_by, groom_name, bride_name, bride_first,
  phone_number, status, price, created_at, updated_at
)
select
  o.id, o.company_id, o.created_by, o.groom_name, o.bride_name,
  coalesce(o.form_data->'brideFirst' = 'true'::jsonb, false),
  o.phone_number, o.status, nullif(to_jsonb(o)->>'price', '')::numeric,
  o.created_at, o.updated_at
from public.orders o
on conflict (legacy_order_id) do nothing;

insert into public.invitations (
  couple_order_id, legacy_order_id, template_code, form_data, status,
  published_path, published_url, management_id, published_at, expires_at,
  rejection_reason, admin_notes, price, created_at, updated_at
)
select
  c.id, o.id, o.template_code, o.form_data, o.status,
  o.published_path, o.published_url, o.management_id, o.published_at,
  o.expires_at, o.rejection_reason, o.admin_notes,
  nullif(to_jsonb(o)->>'price', '')::numeric,
  o.created_at, o.updated_at
from public.orders o
join public.couple_orders c on c.legacy_order_id = o.id
on conflict (legacy_order_id) do nothing;

-- Preserve order_id for existing application code and responses, while adding
-- a direct invitation attribution for the unified RSVP board.
alter table public.order_rsvps
  add column invitation_id bigint references public.invitations(id) on delete set null;
create index order_rsvps_invitation_created_idx
  on public.order_rsvps(invitation_id, created_at desc);

update public.order_rsvps r
set invitation_id = i.id
from public.invitations i
where i.legacy_order_id = r.order_id
  and r.invitation_id is null;

comment on table public.couple_orders is
  'One shared order record per couple; legacy orders are linked through legacy_order_id during migration.';
comment on table public.invitations is
  'Invitation-specific content and URL. Existing orders are copied one-to-one and retain their original links.';
comment on column public.order_rsvps.invitation_id is
  'Invitation attribution for unified RSVP reporting; existing order_id remains unchanged for compatibility.';

commit;
