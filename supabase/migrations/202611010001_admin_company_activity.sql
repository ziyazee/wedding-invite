alter table public.companies
  add column if not exists is_active boolean not null default true;

create table if not exists public.company_pdf_uploads (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  uploaded_by uuid not null references auth.users(id),
  filename text not null,
  created_at timestamptz not null default now()
);

create index if not exists company_pdf_uploads_company_created_idx
  on public.company_pdf_uploads(company_id, created_at desc);

alter table public.company_pdf_uploads enable row level security;

drop policy if exists "clients log own PDF uploads" on public.company_pdf_uploads;
create policy "clients log own PDF uploads" on public.company_pdf_uploads
  for insert to authenticated
  with check (
    company_id = public.current_user_company_id()
    and uploaded_by = auth.uid()
  );

drop policy if exists "admins view PDF upload activity" on public.company_pdf_uploads;
create policy "admins view PDF upload activity" on public.company_pdf_uploads
  for select to authenticated
  using (public.current_user_is_admin());

grant insert (company_id, uploaded_by, filename) on public.company_pdf_uploads to authenticated;
grant select on public.company_pdf_uploads to authenticated;
grant usage, select on sequence public.company_pdf_uploads_id_seq to authenticated;

create or replace function public.admin_company_activity(
  p_month_start timestamptz,
  p_month_end timestamptz
)
returns table (
  company_id bigint,
  company_name text,
  contact_name text,
  email text,
  phone text,
  logo_path text,
  onboarded_at timestamptz,
  is_active boolean,
  total_orders bigint,
  month_orders bigint,
  pdf_uploads bigint,
  last_activity_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.id,
    c.company_name,
    c.contact_name,
    c.email,
    c.phone,
    c.logo_path,
    c.created_at,
    c.is_active,
    coalesce(o.total_orders, 0),
    coalesce(o.month_orders, 0),
    coalesce(p.pdf_uploads, 0),
    greatest(o.last_order_at, p.last_pdf_at)
  from public.companies c
  left join lateral (
    select
      count(*)::bigint as total_orders,
      count(*) filter (where created_at >= p_month_start and created_at < p_month_end)::bigint as month_orders,
      max(created_at) as last_order_at
    from public.orders
    where company_id = c.id
  ) o on true
  left join lateral (
    select count(*)::bigint as pdf_uploads, max(created_at) as last_pdf_at
    from public.company_pdf_uploads
    where company_id = c.id
  ) p on true
  where public.current_user_is_admin() and c.is_active
  order by c.created_at desc, c.company_name;
$$;

revoke all on function public.admin_company_activity(timestamptz, timestamptz) from public;
grant execute on function public.admin_company_activity(timestamptz, timestamptz) to authenticated;

notify pgrst, 'reload schema';
