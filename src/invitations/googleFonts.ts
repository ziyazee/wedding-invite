export const googleFontMap: Record<string, string> = Object.fromEntries(
  GOOGLE_FONTS.map(f => [f.key, f.family])
)

const loaded = new Set<string>()

export function loadGoogleFont(label: string) {
  const id = label.replace(/\s+/g, '+')
  if (loaded.has(id)) return
  loaded.add(id)
  const link = document.createElement('link')
  link.rel = 'stylesheet'
  link.href = `https://fonts.googleapis.com/css2?family=${id}&display=swap`
  document.head.appendChild(link)
}
